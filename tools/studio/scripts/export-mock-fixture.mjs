// Dev-time generator of the mock OpenRouter fixtures (ST-05): tests/studio/fixtures/models.json and mock-replies.json.
// It starts the REAL StarMedia test mock (test/mock.ts, startMock()) and records what it answers over HTTP, so the C++
// mock (tests/studio/mockopenrouter.*) serves the same catalog and test_studio_openrouter can check the C++ answers
// against the TS answers route by route. Nothing is copied by hand; a change in mock.ts shows up as a fixture diff.
//
// Usage (Node 22+, no packages needed):
//   node --experimental-strip-types tools/studio/scripts/export-mock-fixture.mjs [starmedia root] [out dir]
// Defaults: $STARMEDIA_ROOT (or the first argument) and <this repo>/tests/studio/fixtures. Output is deterministic: the mock's
// `created` stamps are relative to its start time (now - N days), so they are rewritten against REFERENCE_NOW below
// (the C++ mock shifts them back to "now - N days" when it serves them), and the per-run port becomes "{base}".
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { execFileSync } from 'node:child_process';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(process.argv[2] || process.env.STARMEDIA_ROOT || (console.error('pass the starmedia checkout as the first argument or set STARMEDIA_ROOT'), process.exit(2)));
const outDir = path.resolve(process.argv[3] || path.join(here, '..', '..', '..', 'tests', 'studio', 'fixtures'));
const mockFile = path.join(root, 'test', 'mock.ts');
const mod = await import(pathToFileURL(mockFile).href);

let head = 'unknown';
try { head = execFileSync('git', ['-C', root, 'log', '-1', '--format=%h %cs', '--', 'test/mock.ts'], { encoding: 'utf8' }).trim(); } catch { /* not a checkout */ }

const REFERENCE_NOW = Date.UTC(2026, 9, 26) / 1000; // 2026-10-26T00:00:00Z
const DAY = 86400;

const mock = await mod.startMock();
const base = mock.url;
const unbase = (v) => JSON.parse(JSON.stringify(v).split(base).join('{base}'));
const call = async (method, p, body) => {
  const res = await fetch(base + p, { method, headers: body === undefined ? {} : { 'Content-Type': 'application/json' }, body: body === undefined ? undefined : JSON.stringify(body) });
  const buf = Buffer.from(await res.arrayBuffer());
  const type = res.headers.get('content-type') ?? '';
  return { status: res.status, type, headers: res.headers, buf, json: /json/.test(type) ? JSON.parse(buf.toString('utf8')) : undefined };
};

try {
  // ---------------- catalog (models.json) ----------------
  const nowSec = Date.now() / 1000;
  const rebase = (m) => (typeof m.created === 'number' ? { ...m, created: REFERENCE_NOW - Math.round((nowSec - m.created) / DAY) * DAY } : m);
  const models = (await call('GET', '/models?output_modalities=all')).json.data.map(rebase);
  const ids = models.map((m) => m.id);
  const imageModels = (await call('GET', '/images/models')).json.data;
  const imageEndpoints = {};
  for (const m of imageModels) imageEndpoints[m.id] = (await call('GET', `/images/models/${m.id}/endpoints`)).json;
  // every id the TS mock says can clone a voice (it answers /models/{id}/endpoints for any id)
  const voiceCloning = [];
  for (const id of ids) {
    const d = (await call('GET', `/models/${id}/endpoints`)).json;
    if ((d.data?.endpoints ?? []).some((e) => e.supports_voice_cloning)) voiceCloning.push(id);
  }
  const videoModels = (await call('GET', '/videos/models')).json.data;
  const credits = (await call('GET', '/credits')).json;
  const catalog = {
    _comment: 'Generated by tools/studio/scripts/export-mock-fixture.mjs from starmedia test/mock.ts; do not edit by hand. created = reference_now - age; the C++ mock serves now - age.',
    source: { repo: 'starmedia', file: 'test/mock.ts', commit: head },
    reference_now: REFERENCE_NOW,
    models,
    voice_cloning: voiceCloning,
    image_models: imageModels,
    image_endpoints: imageEndpoints,
    video_models: videoModels,
    credits,
  };

  // ---------------- canned answers (mock-replies.json) ----------------
  // json_schema names whose TS answer does not depend on the prompt text (the rest are prompt-driven and stay in TS)
  const STATIC_SCHEMAS = ['research', 'outline', 'factcheck', 'legal', 'headlines', 'seo', 'social', 'imagePrompts', 'altText', 'videoScript',
    'newsletter', 'ad_dna', 'ad_ideate', 'ad_translate', 'concepts', 'script', 'script_legacy', 'review', 'ref_dna', 'brand_research',
    'market_research', 'stage_dramatize'];
  const chat = (name, text = 'export') => call('POST', '/chat/completions', {
    model: 'acme/writer-pro', messages: [{ role: 'user', content: text }],
    ...(name ? { response_format: { type: 'json_schema', json_schema: { name, strict: true, schema: { type: 'object' } } } } : {}),
  });
  const json = {};
  const annotations = {};
  for (const name of STATIC_SCHEMAS) {
    const r = (await chat(name)).json;
    json[name] = JSON.parse(r.choices[0].message.content);
    if (r.choices[0].message.annotations) annotations[name] = r.choices[0].message.annotations;
  }
  const article = (await chat(undefined, 'Write the article.')).json.choices[0].message.content;
  const readAloud = (await chat(undefined, 'Rewrite this to read aloud.')).json.choices[0].message.content;
  const sha = (b) => crypto.createHash('sha256').update(b).digest('hex');
  const speech = await call('POST', '/audio/speech', { model: 'acme/tts-1', input: 'Hello there.', voice: 'alloy', response_format: 'mp3' });
  const image = await call('POST', '/images', { model: 'acme/img-1', prompt: 'a red car' });

  // the TS answers the C++ mock must match (test_studio_openrouter tsParity: every TS key present with the same value)
  const parity = [];
  const record = async (name, method, p, body) => {
    const r = await call(method, p, body);
    parity.push({ name, method, path: p, ...(body === undefined ? {} : { body }), status: r.status, content_type: r.type, ...(r.json !== undefined ? { json: unbase(r.json) } : { sha256: sha(r.buf), bytes: r.buf.length }) });
  };
  await record('chat article', 'POST', '/chat/completions', { model: 'acme/writer-pro', messages: [{ role: 'user', content: 'Write the article.' }] });
  await record('chat read aloud', 'POST', '/chat/completions', { models: ['beta/writer-2', 'acme/writer-pro'], messages: [{ role: 'user', content: 'Make it read aloud.' }] });
  await record('chat schema', 'POST', '/chat/completions', { model: 'acme/writer-pro', messages: [{ role: 'user', content: 'x' }], response_format: { type: 'json_schema', json_schema: { name: 'review', strict: true, schema: { type: 'object' } } } });
  await record('chat annotations', 'POST', '/chat/completions', { model: 'acme/writer-pro', messages: [{ role: 'user', content: 'x' }], response_format: { type: 'json_schema', json_schema: { name: 'market_research', strict: true, schema: { type: 'object' } } } });
  await record('images', 'POST', '/images', { model: 'acme/img-1', prompt: 'a red car' });
  await record('video submit', 'POST', '/videos', { model: 'acme/vid-1', prompt: 'a slow pan', duration: 4 });
  await record('video poll', 'GET', '/videos/job1');
  await record('video content', 'GET', '/videos/job1/content');
  await record('speech', 'POST', '/audio/speech', { model: 'acme/tts-1', input: 'Hello there.', voice: 'alloy', response_format: 'mp3' });
  await record('transcription', 'POST', '/audio/transcriptions', { model: 'acme/stt-1', input_audio: { data: 'AAAA', format: 'mp3' }, response_format: 'verbose_json' });
  await record('embeddings', 'POST', '/embeddings', { model: 'acme/embed-1', input: ['Henry County school board', 'Budget approved; teacher pay rises 3 percent!', 'Ünïcode wörds and 42 numbers'], encoding_format: 'float' });
  await record('embeddings single', 'POST', '/embeddings', { model: 'acme/embed-1', input: 'one string input' });
  await record('rerank', 'POST', '/rerank', { model: 'acme/rerank-1', query: 'budget', documents: ['a', 'b', 'c', 'd'], top_n: 2 });
  await record('generation', 'GET', '/generation?id=gen-unknown');
  await record('credits', 'GET', '/credits');
  await record('models endpoints clone', 'GET', '/models/acme/tts-clone/endpoints');
  await record('models endpoints plain', 'GET', '/models/acme/tts-1/endpoints');
  await record('image endpoints', 'GET', '/images/models/acme/img-1/endpoints');
  await record('image endpoints free', 'GET', '/images/models/beta/img-free/endpoints');
  await record('image models', 'GET', '/images/models');
  await record('video models', 'GET', '/videos/models');
  await record('no route', 'GET', '/nope');

  const replies = {
    _comment: 'Generated by tools/studio/scripts/export-mock-fixture.mjs from starmedia test/mock.ts; do not edit by hand.',
    source: { repo: 'starmedia', file: 'test/mock.ts', commit: head },
    article,
    read_aloud: readAloud,
    json,
    annotations,
    speech: { sha256: sha(speech.buf), bytes: speech.buf.length, content_type: speech.type, generation_id: speech.headers.get('x-generation-id') },
    image: { b64: image.json.data[0].b64_json, media_type: image.json.data[0].media_type },
    parity,
  };

  fs.mkdirSync(outDir, { recursive: true });
  fs.writeFileSync(path.join(outDir, 'models.json'), JSON.stringify(catalog, null, 1) + '\n');
  fs.writeFileSync(path.join(outDir, 'mock-replies.json'), JSON.stringify(replies, null, 1) + '\n');
  process.stderr.write(`wrote ${ids.length} models, ${Object.keys(json).length} canned answers, ${parity.length} parity cases from mock.ts ${head}\n`);
} finally {
  await mock.close();
}
